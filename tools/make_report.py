"""Build the paper-ready deliverables from the REAL evaluation outputs.

Reads only artefacts produced by src.evaluate (raw per-target predictions) and
recomputes every number from them, so nothing here can invent a metric.

Outputs
    tables/final_model_comparison.tex   IEEE (booktabs) LaTeX table
    tables/final_model_comparison.md    Markdown table
    tables/ablations.tex                ablation table
    results/final_report.json            one self-contained summary
    figures/roc_curves.png, pr_curves.png, confusion_matrices.png,
            training_curves.png

Usage: python tools/make_report.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd

import config as C
from src.models import MODEL_LABELS
from src.evaluate import IEEE_COLUMNS, METRIC_ORDER, metrics_from

MODEL_ORDER = ["baseline_1dcnn", "baseline_2dcnn", "baseline_lstm",
               "baseline_3dcnn", "pixel_verifynet"]
def load_predictions():
    out = {}
    for name in MODEL_ORDER:
        f = C.RESULTS / f"predictions_{name}.csv"
        if f.exists():
            out[name] = pd.read_csv(f)
    return out


def load_table():
    f = C.RESULTS / "final_metrics.csv"
    if not f.exists():
        raise SystemExit("results/final_metrics.csv missing - run src.evaluate first")
    return pd.read_csv(f)
def dataset_facts():
    splits = pd.read_csv(C.DATASET / "splits.csv")
    per = {}
    for s in ("train", "validation", "test"):
        sub = splits[splits.split == s]
        per[s] = {
            "targets": int(sub["target_id"].nunique()),
            "windows": int(len(sub)),
            "planets": int((sub.label == 1).sum()),
            "false_positives": int((sub.label == 0).sum()),
            "kepler": int((sub.mission == "kepler").sum()),
            "tess": int((sub.mission == "tess").sum()),
        }
    audit_f = C.RESULTS / "label_leakage_audit.json"
    audit = json.loads(audit_f.read_text()) if audit_f.exists() else {}
    cats = {}
    for m in C.MISSIONS:
        f = C.RAW / f"{m}_catalog.csv"
        if f.exists():
            d = pd.read_csv(f)
            cats[m] = {"targets": int(d["target_id"].nunique()),
                       "planets": int((d.label == 1).sum()),
                       "false_positives": int((d.label == 0).sum())}
    return {"per_split": per, "leakage_audit": audit, "catalogs": cats,
            "total_unique_targets": int(splits["target_id"].nunique())}
def latex_metric_table(table):
    rows = []
    for _, r in table.iterrows():
        cells = [str(r["Model"])] + [f"{float(r[c]):.4f}" for c in IEEE_COLUMNS]
        rows.append(" & ".join(cells) + " \\\\")
    head = " & ".join(["Model"] + IEEE_COLUMNS)
    return "\n".join([
        "% Auto-generated by tools/make_report.py from real test predictions.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Comparison of all five models on the held-out test targets "
        "(fixed decision threshold 0.5, no per-model tuning).}",
        "\\label{tab:final_comparison}",
        "\\begin{tabular}{lccccccc}",
        "\\toprule",
        head + " \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ])


def ablation_table():
    f = C.RESULTS / "ablation.csv"
    if not f.exists():
        return None
    d = pd.read_csv(f)
    rows = []
    for _, r in d.iterrows():
        cells = [str(r["configuration"]), "yes" if r["pixel"] else "no",
                 "yes" if r["mask"] else "no", "yes" if r["physics"] else "no",
                 f"{r['accuracy']:.4f}", f"{r['f1']:.4f}", f"{r['roc_auc']:.4f}",
                 f"{r['pr_auc']:.4f}"]
        rows.append(" & ".join(cells) + " \\\\")
    return "\n".join([
        "% Auto-generated by tools/make_report.py.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Branch ablation of PIXEL-VerifyNet on the same test targets.}",
        "\\label{tab:ablation}",
        "\\begin{tabular}{lccccccc}", "\\toprule",
        "Config. & Pixel & Mask & Physics & Acc. & F1 & ROC-AUC & PR-AUC \\\\",
        "\\midrule", *rows, "\\bottomrule", "\\end{tabular}", "\\end{table}",
    ])


def make_figures(preds):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import (average_precision_score, auc, confusion_matrix,
                                 precision_recall_curve, roc_curve)

    C.FIGURES.mkdir(parents=True, exist_ok=True)
    colors = plt.cm.tab10(np.linspace(0, 1, 10))

    fig, ax = plt.subplots(figsize=(5, 4.2))
    for i, (name, d) in enumerate(preds.items()):
        y, p = d["label"].values, d["probability"].values
        if len(set(y.tolist())) > 1:
            fpr, tpr, _ = roc_curve(y, p)
            ax.plot(fpr, tpr, lw=1.6, color=colors[i % 10],
                    label=f"{MODEL_LABELS[name]} (AUC={auc(fpr, tpr):.3f})")
    ax.plot([0, 1], [0, 1], "k--", lw=0.8)
    ax.set_xlabel("False positive rate")
    ax.set_ylabel("True positive rate")
    ax.set_title("ROC - held-out test targets")
    ax.legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    fig.savefig(C.FIGURES / "roc_curves.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(5, 4.2))
    for i, (name, d) in enumerate(preds.items()):
        y, p = d["label"].values, d["probability"].values
        if len(set(y.tolist())) > 1:
            prec, rec, _ = precision_recall_curve(y, p)
            ax.plot(rec, prec, lw=1.6, color=colors[i % 10],
                    label=f"{MODEL_LABELS[name]} (AP={average_precision_score(y, p):.3f})")
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_title("Precision-Recall - held-out test targets")
    ax.legend(fontsize=7, loc="lower left")
    fig.tight_layout()
    fig.savefig(C.FIGURES / "pr_curves.png", dpi=160)
    plt.close(fig)

    n = max(len(preds), 1)
    fig, axes = plt.subplots(1, n, figsize=(2.3 * n, 2.6))
    axes = np.atleast_1d(axes)
    for ax, (name, d) in zip(axes, preds.items()):
        cm = confusion_matrix(d["label"], d["prediction"], labels=[0, 1])
        ax.imshow(cm, cmap="Blues")
        ax.set_xticks([0, 1]); ax.set_yticks([0, 1])
        ax.set_xticklabels(["FP", "PL"]); ax.set_yticklabels(["FP", "PL"])
        ax.set_title(MODEL_LABELS[name], fontsize=8)
        for (r, c), v in np.ndenumerate(cm):
            ax.text(c, r, str(int(v)), ha="center", va="center", fontsize=9)
    fig.tight_layout()
    fig.savefig(C.FIGURES / "confusion_matrices.png", dpi=160)
    plt.close(fig)

    curves = []
    for name in MODEL_ORDER:
        f = C.RESULTS / f"{name}_history.json"
        if f.exists():
            h = json.loads(f.read_text())
            curves.append((name, [e["val_roc_auc"] for e in h]))
    if curves:
        fig, ax = plt.subplots(figsize=(5, 3.6))
        for i, (name, v) in enumerate(curves):
            ax.plot(range(1, len(v) + 1), v, label=MODEL_LABELS[name],
                    color=colors[i % 10])
        ax.set_xlabel("epoch"); ax.set_ylabel("validation ROC-AUC")
        ax.set_title("Training history (identical protocol)")
        ax.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(C.FIGURES / "training_curves.png", dpi=160)
        plt.close(fig)


def main():
    C.ensure_dirs()
    table = load_table()
    order = {m: i for i, m in enumerate(MODEL_ORDER)}
    table = (table.assign(_o=table["model"].map(order))
                  .sort_values("_o").drop(columns="_o").reset_index(drop=True))
    preds = load_predictions()
    if not preds:
        raise SystemExit("no results/predictions_*.csv found - run src.evaluate first")

    # Recompute every metric from the stored probabilities and assert they match
    # src.evaluate exactly. Nothing here can introduce or alter a metric.
    recomputed = {}
    for name, d in preds.items():
        recomputed[name] = metrics_from(d["label"].values, d["probability"].values)
        for k in METRIC_ORDER:
            row = float(table.loc[table.model == name, k].iloc[0])
            assert abs(row - recomputed[name][k]) < 1e-9, (name, k)

    ieee_rows = []
    for _, r in table.iterrows():
        vals = {ieee_c: round(float(r[met_c]), 4)
                for met_c, ieee_c in zip(METRIC_ORDER, IEEE_COLUMNS)}
        ieee_rows.append({"Model": MODEL_LABELS.get(r["model"], r["model"]), **vals})
    ieee = pd.DataFrame(ieee_rows)
    C.TABLES.mkdir(parents=True, exist_ok=True)
    ieee.to_csv(C.TABLES / "final_model_comparison.csv", index=False)
    (C.TABLES / "final_model_comparison.tex").write_text(latex_metric_table(ieee))
    md = table[["model_label"] + METRIC_ORDER].copy()
    (C.TABLES / "final_model_comparison.md").write_text(
        "| " + " | ".join(md.columns) + " |\n"
        + "|" + "|".join(["---"] * len(md.columns)) + "|\n"
        + "\n".join("| " + " | ".join(f"{v:.4f}" if isinstance(v, float) else str(v)
                                      for v in row) + " |"
                    for row in md.itertuples(index=False)) + "\n")
    ab = ablation_table()
    if ab:
        (C.TABLES / "ablations.tex").write_text(ab)

    make_figures(preds)

    report = {"dataset": dataset_facts(),
              "protocol": {"threshold": C.THRESHOLD, "split": "test",
                           "seed": C.SEED, "time_bins": C.TIME_BINS,
                           "height": C.HEIGHT, "width": C.WIDTH},
              "comparison": {MODEL_LABELS.get(r["model"], r["model"]):
                             {k: float(r[k]) for k in METRIC_ORDER}
                             for _, r in table.iterrows()},
              "metrics_recomputed_from_predictions": recomputed,
              "confusion": {n: {k: recomputed[n][k] for k in ("tn", "fp", "fn", "tp")}
                            for n in recomputed}}
    (C.RESULTS / "final_report.json").write_text(json.dumps(report, indent=2))
    inject_readme_results(ieee, report)
    print(ieee.to_string(index=False))
    print(f"\n[make_report] wrote {C.TABLES / 'final_model_comparison.tex'}")
    print(f"[make_report] wrote {C.RESULTS / 'final_report.json'}")


def inject_readme_results(ieee: pd.DataFrame, report: dict):
    """Write the measured table into README.md between the RESULTS markers.

    The README claims results are 'filled in by the pipeline itself, never typed
    by hand'. This enforces it: the block between the markers is replaced with
    the numbers just recomputed from the per-target prediction CSVs.

    Guarded: only the REAL run may touch the real README. The unit tests call
    main() against a synthetic 40-target fixture in a tmp dir, and without this
    guard they would overwrite the published numbers with toy ones.
    """
    readme = ROOT / "README.md"
    if not readme.exists():
        return
    if C.DATASET.resolve() != (ROOT / "data" / "dataset").resolve() \
            or C.RESULTS.resolve() != (ROOT / "results").resolve():
        print("[make_report] not the real dataset/results dir - "
              "README.md left untouched")
        return
    n = report["dataset"].get("total_unique_targets", 0)
    if n < 1000:
        print(f"[make_report] only {n} targets in the report - "
              "README.md left untouched")
        return
    txt = readme.read_text(encoding="utf-8")
    begin = "<!-- RESULTS:BEGIN"
    end = "<!-- RESULTS:END -->"
    i, j = txt.find(begin), txt.find(end)
    if i < 0 or j < 0 or j < i:
        print("[make_report] README.md has no RESULTS markers; skipped")
        return

    d = report["dataset"]
    p = report["protocol"]
    per = d.get("per_split", {})
    tr, va, te = per.get("train", {}), per.get("validation", {}), per.get("test", {})
    lines = [
        begin + " (generated by tools/make_report.py - do not edit by hand) -->",
        "",
        f"**Dataset.** {d.get('total_unique_targets', '?')} unique targets, split "
        f"{tr.get('targets', '?')} train / {va.get('targets', '?')} validation / "
        f"{te.get('targets', '?')} test at the **target** level (zero target overlap).",
        f"Test split: {te.get('planets', '?')} planets / {te.get('false_positives', '?')} "
        f"false positives, {te.get('kepler', '?')} Kepler / {te.get('tess', '?')} TESS.",
        f"Tensors are `{p['time_bins']} × {p['height']} × {p['width']}`; "
        f"threshold `{p['threshold']}`, seed `{p['seed']}`, fixed for every model.",
        "",
        "| " + " | ".join(ieee.columns) + " |",
        "|" + "|".join(["---"] * len(ieee.columns)) + "|",
    ]
    for row in ieee.itertuples(index=False):
        lines.append("| " + " | ".join(
            f"{v:.4f}" if isinstance(v, float) else str(v) for v in row) + " |")
    lines += ["", end]
    readme.write_text(txt[:i] + "\n".join(lines) + txt[j + len(end):], encoding="utf-8")
    print("[make_report] refreshed the results table inside README.md")


if __name__ == "__main__":
    main()